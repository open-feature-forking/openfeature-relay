// Kind is how the generated source wires the item: "sync", "format", "evaluator", "engine", "endpoint", "telemetry",
// "middleware" or "eventsink".
func (i Item) Kind() string {
	switch i.Group {
	case manifest.SyncProviders:
		return "sync"
	case manifest.ConfigurationFormats:
		return "format"
	case manifest.Evaluators:
		return "evaluator"
	case manifest.Engines:
		return "engine"
	case manifest.ServiceEndpoints:
		return "endpoint"
	case manifest.Telemetry:
		return "telemetry"
	case manifest.Middleware:
		return "middleware"
	case manifest.EventSinks:
		return "eventsink"
	}
	return ""
}

var templates = map[string]*template.Template{
	"go.mod":                   template.Must(template.New("go.mod").Parse(goModTemplate)),
	"main.go":                  template.Must(template.New("main.go").Parse(mainTemplate)),
	"components/components.go": template.Must(template.New("components.go").Parse(componentsTemplate)),
	"probe/main.go":            template.Must(template.New("probe.go").Parse(probeTemplate)),
}

