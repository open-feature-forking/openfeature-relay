// Package generate writes the source of a distribution from its manifest: a main module with the main package, the
// components package that wires the factories, the probe that reports them, and go.mod. It writes these files and no
// other (BR-009), and its output is the same for the same manifest.
package generate

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"

	"github.com/open-feature-forking/openfeature-relay/builder/internal/manifest"
)

// Module paths of the relay modules every distribution requires.
const (
	CoreModule    = "github.com/open-feature-forking/openfeature-relay/core"
	RuntimeModule = "github.com/open-feature-forking/openfeature-relay/runtime"
)

// Options are what the Builder supplies besides the manifest.
type Options struct {
	// RuntimeVersion is the version of the runtime module when the manifest does not pin one, and CoreVersion that of
	// the core module. Both default to v0.0.0, which a manifest in a repository resolves through its replaces.
	RuntimeVersion string
	CoreVersion    string
	// GoVersion is the go directive of the generated module; it defaults to 1.27.
	GoVersion string
	// OutputDir, when set, is the directory the source is written to instead of the manifest's output_path.
	OutputDir string
}

// Header is the first line of every generated file. The Builder overwrites a file only when it starts with it.
const Header = "// Code generated by relay-builder; DO NOT EDIT."

// Item is a component of the manifest as the generated source refers to it.
type Item struct {
	Group manifest.Group
	// Module and Version are the component module; Import is the package that holds its factory.
	Module  string
	Version string
	Import  string
	// Alias is the identifier the generated source imports the package as.
	Alias string
	// Replaced is set when the manifest replaces the module by a local path.
	Replaced bool
}

var aliasPrefix = map[manifest.Group]string{
	manifest.SyncProviders:        "sync",
	manifest.ConfigurationFormats: "format",
	manifest.Evaluators:           "evaluator",
	manifest.Engines:              "engine",
	manifest.ServiceEndpoints:     "endpoint",
	manifest.Telemetry:            "telemetry",
	manifest.Middleware:           "middleware",
	manifest.EventSinks:           "eventsink",
}

// Items returns the components of the manifest in manifest order, with the alias each has in the generated source.
func Items(m *manifest.Manifest) []Item {
	replaced := map[string]bool{}
	for _, r := range m.Replaces {
		replaced[r.Module] = true
	}
	var items []Item
	for _, e := range m.Entries() {
		path := e.Entry.Import
		if path == "" {
			path = e.Entry.Module
		}
		items = append(items, Item{
			Group: e.Group, Module: e.Entry.Module, Version: e.Entry.Version, Import: path,
			Alias: fmt.Sprintf("%s%d", aliasPrefix[e.Group], e.Index), Replaced: replaced[e.Entry.Module],
		})
	}
	return items
}

// OutputDir is the directory the source is written to: the manifest's output_path, read relative to the manifest.
func OutputDir(m *manifest.Manifest) string {
	if filepath.IsAbs(m.Dist.OutputPath) {
		return filepath.Clean(m.Dist.OutputPath)
	}
	return filepath.Join(m.Dir(), m.Dist.OutputPath)
}

// OutputDirOf is the directory the source is written to with the options: their OutputDir, else the manifest's.
func OutputDirOf(m *manifest.Manifest, opts Options) string {
	if opts.OutputDir != "" {
		return filepath.Clean(opts.OutputDir)
	}
	return OutputDir(m)
}

// Files are the generated files by their path in the output directory, with the slash as separator.
type Files map[string][]byte

// Render returns the files of the manifest's source: go.mod, main.go and components/components.go.
func Render(m *manifest.Manifest, opts Options) (Files, error) {
	data, out, err := prepare(m, opts)
	if err != nil {
		return nil, err
	}
	for _, r := range m.Replaces {
		data.Replaces = append(data.Replaces, moduleVersion{r.Module, relativeTo(out, m.ReplacePath(r))})
	}
	sort.Slice(data.Replaces, func(i, j int) bool { return data.Replaces[i].Module < data.Replaces[j].Module })
	return execute(sourceTemplates, data)
}

// RenderProbe returns the files of the probe: a module of its own that imports the generated components package of the
// source in sourceDir, replaces every module the manifest replaces by its absolute path, and prints what the factories
// declare. It lives outside the source, so that the source holds only what the Builder generates for the distribution.
func RenderProbe(m *manifest.Manifest, opts Options, sourceDir string) (Files, error) {
	data, _, err := prepare(m, opts)
	if err != nil {
		return nil, err
	}
	abs, err := filepath.Abs(sourceDir)
	if err != nil {
		return nil, err
	}
	data.Replaces = append(data.Replaces, moduleVersion{m.ModulePath(), filepath.ToSlash(abs)})
	for _, r := range m.Replaces {
		target, err := filepath.Abs(m.ReplacePath(r))
		if err != nil {
			return nil, err
		}
		data.Replaces = append(data.Replaces, moduleVersion{r.Module, filepath.ToSlash(target)})
	}
	sort.Slice(data.Replaces, func(i, j int) bool { return data.Replaces[i].Module < data.Replaces[j].Module })
	return execute(probeTemplates, data)
}

func execute(set map[string]*template.Template, data templateData) (Files, error) {
	files := Files{}
	for name, tmpl := range set {
		var buf bytes.Buffer
		if err := tmpl.Execute(&buf, data); err != nil {
			return nil, fmt.Errorf("rendering %s: %w", name, err)
		}
		content := buf.Bytes()
		if strings.HasSuffix(name, ".go") {
			var err error
			if content, err = format.Source(content); err != nil {
				return nil, fmt.Errorf("formatting %s: %w", name, err)
			}
		}
		files[name] = content
	}
	return files, nil
}

// prepare fills the template data that the source and the probe share, and returns the absolute output directory.
func prepare(m *manifest.Manifest, opts Options) (templateData, string, error) {
	if opts.RuntimeVersion == "" {
		opts.RuntimeVersion = "v0.0.0"
	}
	if opts.CoreVersion == "" {
		opts.CoreVersion = "v0.0.0"
	}
	if opts.GoVersion == "" {
		opts.GoVersion = "1.27"
	}
	items := Items(m)
	data := templateData{
		Module: m.ModulePath(), Name: m.Dist.Name, Items: items, ComponentsHint: m.ComponentsHintOn(),
		CoreModule: CoreModule, RuntimeModule: RuntimeModule, GoVersion: opts.GoVersion,
		CmdImport: RuntimeModule + "/cmd",
	}
	if m.Cmd != nil {
		data.CmdImport = m.Cmd.Import
		if data.CmdImport == "" {
			data.CmdImport = m.Cmd.Module
		}
	}
	requires := map[string]string{CoreModule: opts.CoreVersion}
	if m.Cmd == nil {
		requires[RuntimeModule] = opts.RuntimeVersion
	} else {
		requires[m.Cmd.Module] = m.Cmd.Version
	}
	if m.Runtime != nil {
		requires[RuntimeModule] = m.Runtime.Version
	}
	for _, it := range items {
		requires[it.Module] = it.Version
	}
	for module, version := range requires {
		data.Requires = append(data.Requires, moduleVersion{module, version})
	}
	sort.Slice(data.Requires, func(i, j int) bool { return data.Requires[i].Module < data.Requires[j].Module })

	out, err := filepath.Abs(OutputDirOf(m, opts))
	if err != nil {
		return templateData{}, "", err
	}
	return data, out, nil
}

// Write renders the source and writes it to the output directory. Files that already exist there under other names
// stay as they are, and a file of the generated set that does not start with the generated header is refused before
// anything is written: it was not generated by the Builder.
func Write(m *manifest.Manifest, opts Options) (dir string, err error) {
	files, err := Render(m, opts)
	if err != nil {
		return "", err
	}
	dir = OutputDirOf(m, opts)
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		existing, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(name)))
		if err != nil {
			if os.IsNotExist(err) {
				continue
			}
			return "", fmt.Errorf("reading %s: %w", name, err)
		}
		if !bytes.HasPrefix(existing, []byte(Header)) {
			return "", fmt.Errorf("refusing to overwrite %s: it does not start with %q, so the Builder did not generate it",
				filepath.Join(dir, filepath.FromSlash(name)), Header)
		}
	}
	for _, name := range names {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return "", fmt.Errorf("creating the output location: %w", err)
		}
		if err := os.WriteFile(path, files[name], 0o644); err != nil { //nolint:gosec // the source is meant to be read
			return "", fmt.Errorf("writing %s: %w", name, err)
		}
	}
	return dir, nil
}

// WriteProbe renders the probe for the source in sourceDir and writes it to probeDir, which is a directory of its own.
func WriteProbe(m *manifest.Manifest, opts Options, sourceDir, probeDir string) error {
	files, err := RenderProbe(m, opts, sourceDir)
	if err != nil {
		return err
	}
	for name, content := range files {
		path := filepath.Join(probeDir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, content, 0o644); err != nil { //nolint:gosec // a temporary module
			return err
		}
	}
	return nil
}

// relativeTo returns target as a path relative to dir, with slashes; a target on another volume stays absolute.
func relativeTo(dir, target string) string {
	abs, err := filepath.Abs(target)
	if err != nil {
		return filepath.ToSlash(target)
	}
	rel, err := filepath.Rel(dir, abs)
	if err != nil {
		return filepath.ToSlash(abs)
	}
	rel = filepath.ToSlash(rel)
	if rel != "." && !strings.HasPrefix(rel, "../") {
		rel = "./" + rel
	}
	return rel
}

type moduleVersion struct{ Module, Version string }

// Has reports whether the manifest lists a component of the kind (see Item.Kind).
func (d templateData) Has(kind string) bool {
	for _, it := range d.Items {
		if it.Kind() == kind {
			return true
		}
	}
	return false
}

type templateData struct {
	Module, Name, GoVersion   string
	// ComponentsHint is the manifest's components_hint as a Go boolean.
	ComponentsHint bool
	CoreModule, RuntimeModule string
	// CmdImport is the package whose Execute function is the command line of the distribution.
	CmdImport          string
	Items              []Item
	Requires, Replaces []moduleVersion
}
